export type IconName = keyof typeof BITMAPS;

/** One SVG path from the bitmap: each horizontal run of filled cells becomes a rectangle. */
function toPath(rows: readonly string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      const start = x;
      while (row[x] === '#') x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(Object.entries(BITMAPS).map(([k, rows]) => [k, toPath(rows)])) as Record<IconName, string>;

interface Props {
  name: IconName;
  /** Rendered size in CSS pixels; multiples of 12 keep every art pixel the same size. */
  size?: number;
  className?: string;
  label?: string;
}

export const PixelIcon = memo(function PixelIcon({ name, size = 24, className, label }: Props) {
  return (
    <svg
      className={className ? `px-icon ${className}` : 'px-icon'}
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      <path d={PATHS[name]} fill="currentColor" />
    </svg>
  );
});
